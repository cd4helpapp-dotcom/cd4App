// Builds the small logo embedded in CD4's PDFs, from the app logo, with transparent rounded corners.
//   node scripts/generate-pdf-logo.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const Jimp = require('jimp-compact');

const SIZE = 160;
const RADIUS = 35;
// Bounds of the blue rounded square inside the 1254px source, as in generate-splash-logo.mjs.
const SOURCE = { left: 30, top: 22, right: 1229, bottom: 1231 };

const logo = await Jimp.read(new URL('../assets/images/cd4_logo.png', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
logo.crop(SOURCE.left, SOURCE.top, SOURCE.right - SOURCE.left, SOURCE.bottom - SOURCE.top).resize(SIZE, SIZE);
logo.scan(0, 0, SIZE, SIZE, function (x, y, index) {
  const dx = Math.max(RADIUS - x, x - (SIZE - 1 - RADIUS), 0);
  const dy = Math.max(RADIUS - y, y - (SIZE - 1 - RADIUS), 0);
  if (dx * dx + dy * dy > RADIUS * RADIUS) this.bitmap.data[index + 3] = 0;
});
const png = await logo.getBufferAsync('image/png');
const out = new URL('../supabase/functions/_shared/cd4Logo.ts', import.meta.url);
fs.writeFileSync(out, `// Generated by scripts/generate-pdf-logo.mjs.\nexport const CD4_LOGO_PNG_BASE64 = "${png.toString('base64')}"\n`);
console.log(`logo ${png.length} bytes`);
