export type SettingsTranslationKey = keyof typeof EN_TRANSLATIONS;

export const normalizeLanguageCode = (value: unknown): AppLanguageCode => {
  if (typeof value !== 'string') return 'en';
  const normalized = value.trim().toLowerCase();
  if (!normalized) return 'en';
  const direct = LANGUAGE_ALIASES[normalized];
  if (direct) return direct;

  const localePrefix = normalized.split(/[-_]/)[0];
  if (localePrefix && LANGUAGE_ALIASES[localePrefix]) {
    return LANGUAGE_ALIASES[localePrefix];
  }

  if (normalized.includes('hindi') || normalized.includes('हिं')) return 'hi';
  if (normalized.includes('bengali') || normalized.includes('বাংলা')) return 'bn';
  if (normalized.includes('marathi') || normalized.includes('मराठी')) return 'mr';
  if (normalized.includes('tamil') || normalized.includes('தமிழ்')) return 'ta';
  if (normalized.includes('english')) return 'en';

  return 'en';
};

export const getLanguageOptionByCode = (code: AppLanguageCode): AppLanguageOption =>
  APP_LANGUAGE_OPTIONS.find((item) => item.code === code) || APP_LANGUAGE_OPTIONS[0];

export const interpolateTranslation = (
  template: string,
  params?: Record<string, string | number | null | undefined>
): string => {
  if (!template || !params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = params[key];
    return value === null || value === undefined ? '' : String(value);
  });
};

export const translateSettings = (
  language: AppLanguageCode,
  key: SettingsTranslationKey,
  params?: Record<string, string | number | null | undefined>
): string => {
  const map = TRANSLATIONS[language] || TRANSLATIONS.en;
  const fallback = TRANSLATIONS.en[key];
  const template = map[key] || fallback || key;
  return interpolateTranslation(template, params);
};
